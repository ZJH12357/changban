import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const errors=[],requests=[];
try{
 const page=await browser.newPage({viewport:{width:390,height:844}});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))requests.push(r.url());});
 await page.goto((process.env.TEST_ORIGIN||'http://127.0.0.1:3000')+'/?demo=elder');
 await page.getByRole('button',{name:'团团先休息一下',exact:true}).click();
 assert.equal(await page.locator('.pet-widget').count(),0);
 await page.getByRole('button',{name:'找回团团',exact:true}).click();
 await page.locator('.pet-widget').waitFor();
 await page.getByRole('button',{name:'完成到楼下散散步',exact:true}).click();
 await page.getByText('三步体验 · 2/3',{exact:true}).waitFor();
 await page.getByRole('button',{name:'前往家属端查看并提醒',exact:true}).click();
 const stretch=page.locator('.task-row').filter({hasText:'做一会儿轻松伸展'});
 await stretch.getByText('待确认完成',{exact:true}).waitFor();
 await stretch.getByRole('button',{name:'提醒老人：做一会儿轻松伸展',exact:true}).click();
 await page.getByText('三步体验 · 3/3',{exact:true}).waitFor();
 await stretch.getByText(/已发送，等待老人确认/).waitFor();
 await page.getByRole('button',{name:'前往老人端操作',exact:true}).click();
 await page.getByRole('button',{name:'知道了：做一会儿轻松伸展',exact:true}).click();
 await page.getByText('三步体验已完成',{exact:true}).waitFor();
 await page.getByRole('button',{name:'完成做一会儿轻松伸展',exact:true}).waitFor();
 await page.getByRole('button',{name:'查看家属端回执',exact:true}).click();
 await page.locator('.task-row').filter({hasText:'做一会儿轻松伸展'}).getByText(/老人已确认收到/).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.getByRole('button',{name:'收起引导',exact:true}).click();
 await page.getByRole('button',{name:'展开三步体验引导',exact:true}).click();
 await page.getByRole('button',{name:'重置体验',exact:true}).click();
 await page.getByRole('button',{name:'确认重置体验',exact:true}).click();
 await page.getByText('三步体验 · 1/3',{exact:true}).waitFor();
 await page.getByRole('button',{name:'跳过引导',exact:true}).click();
 await page.getByRole('button',{name:'体验老人端',exact:true}).click();
 await page.locator('.pet-touch').press('Enter');
 await page.locator('.pet-bubble').waitFor();
 const bubble=await page.locator('.pet-bubble').boundingBox(),nav=await page.locator('.bottom-nav').boundingBox();
 assert.ok(bubble.y+bubble.height<=nav.y,'Pet bubble must stay above navigation');
 await page.screenshot({path:'outputs/care-ux-mobile.png'});
 assert.deepEqual(requests,[]);assert.deepEqual(errors,[]);
 console.log('PASS: rest/find, guided real sandbox actions, nudge receipt distinct from completion, reset/skip, mobile navigation safety, no real API traffic.');
}finally{await browser.close();}
