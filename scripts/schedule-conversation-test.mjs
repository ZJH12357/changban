import assert from 'node:assert/strict';
import { registerHooks } from 'node:module';
registerHooks({resolve(s,c,next){if((c.parentURL?.endsWith('/lib/schedule-conversation.ts')||c.parentURL?.endsWith('/lib/demo.ts'))&&s==='./care')return {url:new URL('../lib/care.ts',import.meta.url).href,shortCircuit:true};return next(s,c);}});
const {scheduleTurn,draftPlan}=await import('../lib/schedule-conversation.ts');
const {createDemoStore}=await import('../lib/demo.ts');
const day='2026-10-23',now=day+'T04:00:00Z';
const turn=(d,t)=>scheduleTurn(d,t,day,now);
let r=turn({},'想去公园散步');assert.equal(r.ready,false);assert.match(r.reply,/哪一天/);
r=turn(r.draft,'明天');assert.match(r.reply,/几点/);
r=turn(r.draft,'下午四点半');assert.equal(r.draft.time,'16:30');assert.match(r.reply,/这一次/);
r=turn(r.draft,'每天');assert.equal(r.draft.date,'2026-10-24');assert.equal(r.ready,true);
r=turn(r.draft,'不对，改成后天');assert.equal(r.draft.date,'2026-10-25');assert.equal(r.draft.title,'去公园散步');
r=turn(r.draft,'改成下午五点');assert.equal(r.draft.time,'17:00');assert.equal(draftPlan(r.draft).title,'去公园散步');
assert.deepEqual(turn(r.draft,'算了').draft,{});
assert.equal(turn({},'2026-02-30下午四点散步').ready,false);
assert.equal(turn({},'明天25:90散步').ready,false);
assert.equal(turn({},'明天四点散步').ready,false);
assert.equal(turn({},'今天上午八点散步只提醒一次').ready,false);
assert.equal(turn({},'明天上午九点下午四点散步').ready,false);
assert.equal(turn({},'删除喝水日程').ready,false);
const store=createDemoStore(new Date(now));const transport=store.transport('elder');const plan=draftPlan(r.draft),requestId=crypto.randomUUID();
const call=(role,p)=>store.transport(role)('/api/care',{method:'POST',body:JSON.stringify(p)});
assert.equal((await call('elder',{action:'plan',plan})).status,400);
assert.equal((await call('caregiver',{action:'elderPlan',plan})).status,400);
assert.equal((await call('elder',{action:'elderPlan',plan,requestId})).status,200);
assert.equal((await call('elder',{action:'elderPlan',plan,requestId})).status,200);
assert.equal(store.view('elder').plans.filter(p=>p.title===plan.title).length,1);
assert.equal((await call('caregiver',{action:'task',id:'walk',status:'done'})).status,400);
console.log('Schedule conversation: clarification, correction, cancellation, validation, permissions and retry deduplication passed.');
