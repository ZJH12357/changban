import assert from 'node:assert/strict';
import { buildDailyHistory } from '../lib/care.ts';
const iso=(day,time='00:00')=>new Date(`${day}T${time}:00+08:00`).toISOString();
const initial={sequence:1,reminder:'walk',title:'原来的散步',kind:'activity',time:'16:00',frequency:'daily',date:'2026-10-08',weekday:4,note:'旧备注',active:1,effective:iso('2026-10-08')};
const changed={...initial,sequence:2,title:'改名后的散步',time:'17:00',note:'新备注',effective:iso('2026-10-10','10:00')};
const archived={...changed,sequence:3,active:0,effective:iso('2026-10-11','10:00')};
const revisions=[initial,changed,archived];
const completed={reminder:'walk',date:'2026-10-09',status:'done',snooze:null,updated:iso('2026-10-09','16:10'),title:'当前名称不能覆盖旧记录',time:'17:00',kind:'activity',note:''};
let day=buildDailyHistory('2026-10-09','2026-10-08',revisions,[completed]);
assert.equal(day.total,1);assert.equal(day.done,1);assert.equal(day.rate,100);assert.equal(day.tasks[0].title,'原来的散步');assert.equal(day.tasks[0].time,'16:00');
day=buildDailyHistory('2026-10-08','2026-10-08',revisions,[completed]);
assert.equal(day.pending,1);assert.equal(day.done,0);assert.equal(day.rate,0,'Completion on another date must not leak backwards.');
day=buildDailyHistory('2026-10-10','2026-10-08',revisions,[completed]);
assert.equal(day.tasks[0].title,'改名后的散步');assert.equal(day.pending,1,'An unopened day must still have scheduled, unrecorded tasks.');
day=buildDailyHistory('2026-10-11','2026-10-08',revisions,[]);
assert.equal(day.total,0);assert.equal(day.cancelled,1);assert.equal(day.tasks[0].status,'cancelled');assert.equal(day.rate,null);
assert.equal(buildDailyHistory('2026-10-12','2026-10-08',revisions,[]).tasks.length,0);
const beforeRename={...completed,date:'2026-10-10',updated:iso('2026-10-10','09:00')};
assert.equal(buildDailyHistory('2026-10-10','2026-10-08',revisions,[beforeRename]).tasks[0].title,'原来的散步');
const snoozed={...completed,status:'snoozed',snooze:iso('2026-10-09','16:20')};
assert.equal(buildDailyHistory('2026-10-09','2026-10-08',revisions,[snoozed]).pending,1);
assert.equal(buildDailyHistory('2026-10-09','2026-10-08',revisions,[{...completed,status:'pending'}]).done,0);
const legacy={...completed,date:'2026-10-07',updated:iso('2026-10-07','16:00')};
day=buildDailyHistory('2026-10-07','2026-10-08',revisions,[legacy]);
assert.equal(day.coverage,'legacy');assert.equal(day.rate,null);assert.equal(day.done,1);assert.equal(day.tasks[0].legacy,true);assert.equal(day.tasks[0].title,'原来的散步');
assert.equal(buildDailyHistory('2026-10-06','2026-10-08',revisions,[]).coverage,'legacy');
const once={...initial,reminder:'once',sequence:4,frequency:'once',date:'2026-10-10',effective:iso('2026-10-08')};
assert.equal(buildDailyHistory('2026-10-09','2026-10-08',[once],[]).total,0);
assert.equal(buildDailyHistory('2026-10-10','2026-10-08',[once],[]).total,1);
assert.equal(buildDailyHistory('2026-10-11','2026-10-08',[once],[]).total,0);
const weekly={...initial,reminder:'weekly',frequency:'weekly',weekday:4};
assert.equal(buildDailyHistory('2026-10-15','2026-10-08',[weekly],[]).total,1);
assert.equal(buildDailyHistory('2026-10-16','2026-10-08',[weekly],[]).total,0);
console.log('PASS: per-day full and legacy history, untouched days, daily/once/weekly recurrence, edits/archives, immutable action-time titles, undo/snooze, and honest completion rates.');
