import assert from 'node:assert/strict';
import { DEFAULT_PET, PET_CHAT_WINDOW_MS, activeFamilyNudges, familyPetBrief, parsePetPreferences, clampPet, clearPetPath, nearestPetTask, pendingPetTasks, petDueAt, petOccurrenceKey, petSingleClickKind, petProgressSummary, petTaskProgress } from '../lib/pet.ts';

assert.deepEqual(parsePetPreferences(null), DEFAULT_PET);
assert.deepEqual([DEFAULT_PET.mode, DEFAULT_PET.activity, DEFAULT_PET.interaction, DEFAULT_PET.size], ['roam', 'lively', 'high', 'medium']);
assert.deepEqual(parsePetPreferences({}), DEFAULT_PET);
assert.deepEqual(parsePetPreferences({ activity: 'invalid', interaction: 'invalid' }), DEFAULT_PET);
assert.equal(parsePetPreferences({ activity: 'balanced', interaction: 'normal' }).activity, 'balanced', 'Saved user preferences must be preserved.');
assert.equal(parsePetPreferences({ activity: 'balanced', interaction: 'normal' }).interaction, 'normal');
assert.deepEqual(parsePetPreferences({ mode: 'bad', size: 'giant', enabled: 'false', sound: true, anchor: { x: Infinity, y: 3 } }), { ...DEFAULT_PET, sound: true });
assert.deepEqual(parsePetPreferences({ mode: 'fixed', enabled: false, anchor: { x: -2, y: 9 } }).anchor, { x: 0, y: 1 });
assert.deepEqual(clampPet({ x: -50, y: 1000 }, { x: 12, y: 90, width: 200, height: 300 }), { x: 12, y: 390 });
const obstacle = { x: 70, y: 0, width: 20, height: 100 };
assert.equal(clearPetPath({ x: 0, y: 20 }, { x: 150, y: 20 }, 20, [obstacle]), false, 'A clear endpoint must not allow walking through a button.');
assert.equal(clearPetPath({ x: 0, y: 130 }, { x: 150, y: 130 }, 20, [obstacle]), true);
const task = { id: 'r1', title: '散步', time: '09:00', kind: 'activity', frequency: 'daily', date: '2026-10-15', weekday: 4, note: '', status: 'pending' };
const snoozed = { ...task, id: 'r2', time: '08:00', status: 'snoozed', snooze: '2026-10-15T01:10:00.000Z' };
assert.equal(petDueAt(task, '2026-10-15'), Date.parse('2026-10-15T01:00:00Z'));
assert.equal(petDueAt(snoozed, '2026-10-15'), Date.parse(snoozed.snooze));
assert.deepEqual(pendingPetTasks([snoozed, { ...task, id: 'done', status: 'done' }, task], '2026-10-15').map(t => t.id), ['r1', 'r2']);
assert.notEqual(petOccurrenceKey(task, '2026-10-15'), petOccurrenceKey(task, '2026-10-16'));
assert.notEqual(petOccurrenceKey(task, '2026-10-15'), petOccurrenceKey({ ...task, status: 'snoozed', snooze: snoozed.snooze }, '2026-10-15'));
const at = time => Date.parse('2026-10-15T' + time + ':00+08:00');
assert.equal(nearestPetTask([task, snoozed], '2026-10-15', at('09:08')).id, 'r2');
assert.equal(nearestPetTask([task, snoozed], '2026-10-15', at('08:55')).id, 'r1');
assert.equal(nearestPetTask([{ ...task, status: 'done' }, snoozed], '2026-10-15', at('09:00')).id, 'r2');
assert.equal(nearestPetTask([], '2026-10-15', at('09:00')), undefined);
assert.equal(nearestPetTask([{ ...task, status: 'done' }], '2026-10-15', at('09:00')), undefined);
assert.equal(petSingleClickKind(null, 1000), 'reminder');
assert.equal(petSingleClickKind(1000, 1001), 'chat');
assert.equal(petSingleClickKind(1000, 1000 + PET_CHAT_WINDOW_MS - 1), 'chat');
assert.equal(petSingleClickKind(1000, 1000 + PET_CHAT_WINDOW_MS), 'reminder');
assert.equal(petSingleClickKind(1000, 999), 'reminder');
assert.equal(petTaskProgress(task, '2026-10-15', at('08:59')), 'upcoming');
assert.equal(petTaskProgress(task, '2026-10-15', at('09:00')), 'overdue');
assert.equal(petTaskProgress({ ...task, status: 'done' }, '2026-10-15', at('08:00')), 'done');
assert.equal(petTaskProgress(snoozed, '2026-10-15', at('09:05')), 'upcoming', 'Snoozed tasks must not be falsely marked overdue.');
assert.equal(petTaskProgress(snoozed, '2026-10-15', at('09:11')), 'overdue');
assert.deepEqual(petProgressSummary([task, snoozed, { ...task, status: 'done' }], '2026-10-15', at('09:05')), { done: 1, upcoming: 1, overdue: 1 });
const state = { family: { name: '测试阿姨' }, tasks: [task, snoozed, { ...task, id: 'done', status: 'done' }], today: '2026-10-15' };
assert.match(familyPetBrief(state, at('09:05')), /已记录完成 1\/3 项，1 项时间未到，1 项待确认完成/);
assert.match(familyPetBrief({ ...state, tasks: [{ ...task, status: 'done' }] }, at('09:05')), /全部完成/);
assert.match(familyPetBrief({ ...state, tasks: [] }, at('09:05')), /没有日程/);
const nudge = { id: 'n1', reminder: task.id, date: state.today, due: new Date(petDueAt(task, state.today)).toISOString(), seen: null };
assert.equal(activeFamilyNudges({ ...state, nudges: [nudge] }).length, 1);
assert.equal(activeFamilyNudges({ ...state, nudges: [{ ...nudge, seen: '2026-10-15T01:05:00Z' }] }).length, 0);
assert.equal(activeFamilyNudges({ ...state, nudges: [{ ...nudge, date: '2026-10-14' }] }).length, 0);
assert.equal(activeFamilyNudges({ ...state, tasks: [{ ...task, status: 'done' }], nudges: [nudge] }).length, 0);
assert.equal(activeFamilyNudges({ ...state, tasks: [{ ...task, time: '10:00' }], nudges: [nudge] }).length, 0);
console.log('PASS: pet preferences, bounds, obstacle paths, nearest pending/snoozed task, empty agenda, occurrence keys and 15-second chat boundary.');
console.log('PASS: caregiver completion/upcoming/overdue summary, snooze timing and invalidated/acknowledged nudge filtering.');
