import assert from 'node:assert/strict';
import { addCalendarDays, nextScheduledDate, scheduled, scheduleDateLabel, shanghaiDate, upcomingSchedules } from '../lib/care.ts';
const r={id:'test',title:'test',kind:'other',time:'09:00',frequency:'daily',date:'2026-09-17',weekday:4,note:''};
assert.equal(scheduled(r,'2026-09-16'),false);
assert.equal(scheduled(r,'2026-09-17'),true);
assert.equal(scheduled(r,'2026-09-18'),true);
assert.equal(scheduled({...r,frequency:'once'},'2026-09-18'),false);
assert.equal(scheduled({...r,frequency:'weekly'},'2026-09-24'),true);
assert.equal(scheduled({...r,frequency:'weekly'},'2026-09-25'),false);
assert.equal(shanghaiDate(new Date('2026-09-17T15:59:59Z')),'2026-09-17');
assert.equal(shanghaiDate(new Date('2026-09-17T16:00:00Z')),'2026-09-18');
console.log('PASS: daily/once/weekly recurrence, start date, Shanghai midnight.');
assert.equal(addCalendarDays('2026-12-31',1),'2027-01-01');
assert.equal(addCalendarDays('2028-02-28',1),'2028-02-29');
assert.equal(nextScheduledDate({...r,frequency:'once',date:'2026-10-16'},'2026-10-16'),'2026-10-16');
assert.equal(nextScheduledDate({...r,frequency:'once',date:'2026-10-14'},'2026-10-16'),null);
assert.equal(nextScheduledDate({...r,date:'2026-11-01'},'2026-10-16'),'2026-11-01');
assert.equal(nextScheduledDate({...r,frequency:'weekly',weekday:4},'2026-10-16'),'2026-10-22');
assert.equal(nextScheduledDate({...r,frequency:'weekly',weekday:0,date:'2026-10-20'},'2026-10-16'),'2026-10-25');
const shopping={...r,id:'shopping',title:'一起逛街',frequency:'once',date:'2026-10-16',time:'16:00'};
const future=upcomingSchedules([shopping,r,{...r,id:'past',frequency:'once',date:'2026-10-14'}],'2026-10-15');
assert.deepEqual(future.map(x=>[x.plan.id,x.day]),[['test','2026-10-16'],['shopping','2026-10-16']]);
assert.equal(scheduled(shopping,'2026-10-15'),false);
assert.equal(scheduled(shopping,'2026-10-16'),true);
assert.equal(scheduled(shopping,'2026-10-17'),false);
assert.equal(scheduleDateLabel('2026-10-16','2026-10-15'),'明天 · 2026-10-16');
console.log('PASS: future once/daily/weekly previews, expired exclusion, start dates, sorting, leap/year rollover and today-only completion boundary.');
