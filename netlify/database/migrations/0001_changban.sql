-- Netlify-only PostgreSQL schema. The existing drizzle/ SQLite migrations are
-- deliberately unchanged. Text ISO timestamps preserve the shared API format.
CREATE TABLE app_users (
  id text PRIMARY KEY, username text NOT NULL UNIQUE,
  password_hash text NOT NULL, salt text NOT NULL,
  role text NOT NULL CHECK (role IN ('elder','caregiver')), created text NOT NULL
);
CREATE TABLE sessions (
  token_hash text PRIMARY KEY, "user" text NOT NULL REFERENCES app_users(id),
  expires text NOT NULL, created text NOT NULL
);
CREATE INDEX sessions_user ON sessions("user");
CREATE INDEX sessions_expires ON sessions(expires);
CREATE TABLE families (
  id text PRIMARY KEY, owner text NOT NULL UNIQUE REFERENCES app_users(id),
  name text NOT NULL, city text NOT NULL, share integer NOT NULL DEFAULT 1,
  check_time text NOT NULL DEFAULT '10:00', invite text NOT NULL UNIQUE, created text NOT NULL
);
CREATE TABLE members (
  "user" text PRIMARY KEY REFERENCES app_users(id), family text NOT NULL REFERENCES families(id),
  role text NOT NULL CHECK (role IN ('elder','caregiver')), name text NOT NULL,
  phone text NOT NULL DEFAULT '', relation text NOT NULL DEFAULT ''
);
CREATE TABLE reminders (
  id text PRIMARY KEY, family text NOT NULL REFERENCES families(id),
  title text NOT NULL, kind text NOT NULL, time text NOT NULL,
  frequency text NOT NULL, date text NOT NULL, weekday integer NOT NULL,
  note text NOT NULL, active integer NOT NULL DEFAULT 1
);
CREATE INDEX reminders_family ON reminders(family);
CREATE TABLE occurrences (
  id text PRIMARY KEY, family text NOT NULL REFERENCES families(id),
  reminder text NOT NULL REFERENCES reminders(id), date text NOT NULL,
  status text NOT NULL, snooze text, updated text NOT NULL,
  UNIQUE(reminder,date)
);
CREATE INDEX occurrence_family_day ON occurrences(family,date);
CREATE TABLE checkins (
  id text PRIMARY KEY, family text NOT NULL REFERENCES families(id),
  date text NOT NULL, mood text NOT NULL, updated text NOT NULL, UNIQUE(family,date)
);
CREATE TABLE requests (
  id text PRIMARY KEY, family text NOT NULL REFERENCES families(id),
  status text NOT NULL, created text NOT NULL, seen text, resolved text
);
CREATE INDEX requests_family ON requests(family);
CREATE TABLE records (
  id text PRIMARY KEY, family text NOT NULL REFERENCES families(id),
  date text NOT NULL, mood text NOT NULL, sleep double precision NOT NULL,
  systolic integer, diastolic integer, note text NOT NULL, created text NOT NULL,
  UNIQUE(family,date)
);
CREATE TABLE family_nudges (
  id text PRIMARY KEY, family text NOT NULL REFERENCES families(id),
  reminder text NOT NULL REFERENCES reminders(id), date text NOT NULL,
  sender_name text NOT NULL, sender_relation text NOT NULL,
  due text NOT NULL, created text NOT NULL, seen text, UNIQUE(reminder,date)
);
CREATE INDEX family_nudges_family_day ON family_nudges(family,date);
CREATE TABLE history_tracking (
  family text PRIMARY KEY REFERENCES families(id), start_date text NOT NULL, started_at text NOT NULL
);
CREATE TABLE reminder_revisions (
  sequence integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family text NOT NULL REFERENCES families(id), reminder text NOT NULL REFERENCES reminders(id),
  effective text NOT NULL, title text NOT NULL, kind text NOT NULL, time text NOT NULL,
  frequency text NOT NULL, date text NOT NULL, weekday integer NOT NULL,
  note text NOT NULL, active integer NOT NULL
);
CREATE INDEX revision_family_time ON reminder_revisions(family,effective);
CREATE INDEX revision_reminder_time ON reminder_revisions(reminder,effective);
